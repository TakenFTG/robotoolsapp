/**
 * Writes src/lib/theme/m3-tokens.css: every Material 3 colour role, for light and dark,
 * generated from one seed colour. Uses the fidelity scheme so the primary stays close to
 * the brand blue instead of being toned down. Run with `bun run tokens` after changing SEED.
 *
 * The output is committed, so the build never depends on this script.
 */
import {
	argbFromHex,
	customColor,
	DynamicColor,
	Hct,
	hexFromArgb,
	MaterialDynamicColors,
	SchemeFidelity
} from '@material/material-color-utilities';
import { writeFileSync } from 'node:fs';
import { join } from 'node:path';

// VEX IQ blue.
const SEED = '#0077C8';

// Status colours the app relies on (attendance, scoring, warnings). They are nudged
// towards the seed so they sit with it, but stay recognisably green and amber.
const CUSTOM = [
	{ name: 'success', value: '#2E7D32' },
	{ name: 'warning', value: '#B26A00' }
];

const ROLES: Record<string, DynamicColor> = {
	primary: MaterialDynamicColors.primary,
	'on-primary': MaterialDynamicColors.onPrimary,
	'primary-container': MaterialDynamicColors.primaryContainer,
	'on-primary-container': MaterialDynamicColors.onPrimaryContainer,
	'inverse-primary': MaterialDynamicColors.inversePrimary,
	secondary: MaterialDynamicColors.secondary,
	'on-secondary': MaterialDynamicColors.onSecondary,
	'secondary-container': MaterialDynamicColors.secondaryContainer,
	'on-secondary-container': MaterialDynamicColors.onSecondaryContainer,
	tertiary: MaterialDynamicColors.tertiary,
	'on-tertiary': MaterialDynamicColors.onTertiary,
	'tertiary-container': MaterialDynamicColors.tertiaryContainer,
	'on-tertiary-container': MaterialDynamicColors.onTertiaryContainer,
	error: MaterialDynamicColors.error,
	'on-error': MaterialDynamicColors.onError,
	'error-container': MaterialDynamicColors.errorContainer,
	'on-error-container': MaterialDynamicColors.onErrorContainer,
	background: MaterialDynamicColors.background,
	'on-background': MaterialDynamicColors.onBackground,
	surface: MaterialDynamicColors.surface,
	'surface-dim': MaterialDynamicColors.surfaceDim,
	'surface-bright': MaterialDynamicColors.surfaceBright,
	'surface-container-lowest': MaterialDynamicColors.surfaceContainerLowest,
	'surface-container-low': MaterialDynamicColors.surfaceContainerLow,
	'surface-container': MaterialDynamicColors.surfaceContainer,
	'surface-container-high': MaterialDynamicColors.surfaceContainerHigh,
	'surface-container-highest': MaterialDynamicColors.surfaceContainerHighest,
	'on-surface': MaterialDynamicColors.onSurface,
	'surface-variant': MaterialDynamicColors.surfaceVariant,
	'on-surface-variant': MaterialDynamicColors.onSurfaceVariant,
	'inverse-surface': MaterialDynamicColors.inverseSurface,
	'inverse-on-surface': MaterialDynamicColors.inverseOnSurface,
	outline: MaterialDynamicColors.outline,
	'outline-variant': MaterialDynamicColors.outlineVariant,
	shadow: MaterialDynamicColors.shadow,
	scrim: MaterialDynamicColors.scrim,
	'surface-tint': MaterialDynamicColors.surfaceTint
};

function block(isDark: boolean): string[] {
	const scheme = new SchemeFidelity(Hct.fromInt(argbFromHex(SEED)), isDark, 0);
	const lines = Object.entries(ROLES).map(([name, color]) => `\t--md-sys-color-${name}: ${hexFromArgb(color.getArgb(scheme))};`);
	for (const custom of CUSTOM) {
		const group = customColor(argbFromHex(SEED), { ...custom, value: argbFromHex(custom.value), blend: true });
		const g = isDark ? group.dark : group.light;
		lines.push(
			`\t--md-ext-color-${custom.name}: ${hexFromArgb(g.color)};`,
			`\t--md-ext-color-on-${custom.name}: ${hexFromArgb(g.onColor)};`,
			`\t--md-ext-color-${custom.name}-container: ${hexFromArgb(g.colorContainer)};`,
			`\t--md-ext-color-on-${custom.name}-container: ${hexFromArgb(g.onColorContainer)};`
		);
	}
	return lines;
}

const light = block(false);
const dark = block(true);

// Strong fills keep their light-scheme colour in dark mode, because their text is a fixed
// white. These copies let app.css point at them from inside `.dark`.
const FIXED = ['primary', 'error'];
const fixed = light
	.filter((line) => FIXED.some((role) => line.includes(`--md-sys-color-${role}:`)) || /--md-ext-color-(success|warning):/.test(line))
	.map((line) => line.replace(/--md-(sys|ext)-color-/, '--md-fixed-'));

const css = `/* Generated by scripts/generate-m3-tokens.ts from seed ${SEED}. Do not edit by hand. */

:root {
${light.join('\n')}
${fixed.join('\n')}
}

.dark {
${dark.join('\n')}
}

/* Paper has no dark mode: print always uses the light scheme. */
@media print {
	.dark {
${light.map((l) => '\t' + l).join('\n')}
	}
}
`;

writeFileSync(join(import.meta.dirname, '../src/lib/theme/m3-tokens.css'), css);
console.log(`Wrote m3-tokens.css from ${SEED}`);
